"""Aggregate Kaggle runs into paper tables.

Put each downloaded <RUN_ID>.zip (or its unpacked folder) into research/runs/, then:
    python aggregate_runs.py [runs_dir] [out_dir]
Writes out_dir/{runs_index.csv, main_table.csv, shift_table.csv, paired_table.csv, per_class_delta.csv, summary.md}.
Refuses to aggregate runs whose dataset or split fingerprints differ.
"""
import json
import sys
import zipfile
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RUNS = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / "runs"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else HERE / "aggregated"
OUT.mkdir(parents=True, exist_ok=True)

for z in sorted(RUNS.glob("*.zip")):                       # unpack new zips once
    if not (RUNS / z.stem).exists():
        with zipfile.ZipFile(z) as zf:
            zf.extractall(RUNS)

runs = []
for cfg_path in sorted(RUNS.glob("*/experiment_config.json")):
    run_dir = cfg_path.parent
    cfg = json.loads(cfg_path.read_text())
    d = cfg["derived"]
    runs.append({"run_id": cfg["run_id"], "dir": run_dir, "arch": d["arch"], "seed": d["seed"],
                 "notebook_version": cfg["notebook_version"], "started_utc": cfg["run_started_utc"],
                 "dataset_fp": d["dataset_fingerprint"], "split_fp": d["split_fingerprint"],
                 "torch": cfg["environment"]["torch"], "gpus": ";".join(g["name"] for g in cfg["environment"]["gpus"]),
                 "quant_engine": d["quantization"]["engine"], "pretrained_effective": d["pretrained_effective"],
                 "best_ckpt": json.dumps(d["best_checkpoint"]), "shift": json.dumps(d["shift_test_sets"]),
                 "n_errors": len(json.loads((run_dir / "reports" / "errors.json").read_text()))})
if not runs:
    sys.exit(f"No runs found in {RUNS}")
idx = pd.DataFrame(runs)
idx.drop(columns=["dir"]).to_csv(OUT / "runs_index.csv", index=False)
for col in ("dataset_fp", "split_fp"):
    if idx[col].nunique() != 1:
        sys.exit(f"REFUSING: runs differ in {col}:\n{idx[['run_id', col]]}")

bench = pd.concat([pd.read_csv(r["dir"] / "reports" / "benchmark_results.csv") for r in runs], ignore_index=True)
shift = pd.concat([pd.read_csv(r["dir"] / "reports" / "shift_results.csv") for r in runs], ignore_index=True)
ok = bench[bench["status"] == "ok"]

def mean_std(df, keys, cols):
    g = df.groupby(keys, sort=False)
    out = g.size().rename("n_runs").to_frame()
    for c in cols:
        if c in df.columns:
            out[f"{c}_mean"] = g[c].mean()
            out[f"{c}_std"] = g[c].std(ddof=1)
    return out.reset_index()

main_cols = ["accuracy", "f1_macro", "precision_macro", "recall_macro", "ece", "nll", "brier", "model_size_mb",
             "params_reported", "stored_weight_elements", "cpu_latency_1t_ms", "cpu_latency_Nt_ms", "gpu_latency_bs1_ms",
             "gpu_throughput_img_s", "flip_rate_vs_fp32", "delta_accuracy", "delta_f1_macro"]
main = mean_std(ok, ["arch", "experiment"], main_cols)
scope = ok.groupby(["arch", "experiment"])["quantization_scope"].agg(lambda s: " | ".join(sorted(set(s.fillna("n/a").astype(str))))).reset_index()
main = main.merge(scope, on=["arch", "experiment"], how="left")
main.to_csv(OUT / "main_table.csv", index=False)

paired_cols = [c for c in ("run_id", "arch", "seed", "experiment", "flip_rate_vs_fp32", "mcnemar_b_fp32_right_variant_wrong",
                           "mcnemar_c_fp32_wrong_variant_right", "mcnemar_p", "delta_accuracy", "delta_accuracy_ci_low",
                           "delta_accuracy_ci_high", "delta_f1_macro", "delta_f1_ci_low", "delta_f1_ci_high") if c in ok.columns]
ok[ok["experiment"] != "FP32"][paired_cols].to_csv(OUT / "paired_table.csv", index=False)

shift_tab = mean_std(shift, ["arch", "experiment", "test_set", "protocol"], ["accuracy", "f1_macro", "ece", "flip_rate_vs_fp32"])
shift_tab.to_csv(OUT / "shift_table.csv", index=False)

pcs = []
for r in runs:
    p = pd.read_csv(r["dir"] / "reports" / "per_class_f1.csv")
    p.insert(0, "run_id", r["run_id"])
    p.insert(1, "arch", r["arch"])
    pcs.append(p)
per_class = pd.concat(pcs, ignore_index=True)
dcols = [c for c in per_class.columns if c.startswith("delta_f1__")]
per_class.groupby(["arch", "class_name"])[["support"] + dcols].mean().reset_index().to_csv(OUT / "per_class_delta.csv", index=False)

def fmt(m, s, d=4):
    return "n/a" if pd.isna(m) else (f"{m:.{d}f}" if pd.isna(s) else f"{m:.{d}f} ± {s:.{d}f}")

lines = ["# Aggregated results (generated by aggregate_runs.py, do not edit by hand)", "",
         f"Runs: {len(idx)} | archs: {sorted(idx['arch'].unique())} | seeds per arch: "
         f"{idx.groupby('arch')['seed'].apply(sorted).to_dict()}",
         f"Dataset fingerprint {idx['dataset_fp'].iloc[0][:16]}…, split fingerprint {idx['split_fp'].iloc[0][:16]}… (identical across runs)",
         f"Notebook versions: {sorted(idx['notebook_version'].unique())} | torch: {sorted(idx['torch'].unique())} | "
         f"logged errors: {int(idx['n_errors'].sum())}", "",
         "## PlantVillage test (mean ± std over seeds)", "",
         "| arch | variant | n | accuracy | macro-F1 | ECE | size MB | params() | stored weights | CPU 1t ms | flip vs FP32 |",
         "|---|---|---|---|---|---|---|---|---|---|---|"]
for _, r in main.iterrows():
    lines.append(f"| {r['arch']} | {r['experiment']} | {r['n_runs']} | {fmt(r['accuracy_mean'], r['accuracy_std'])} | "
                 f"{fmt(r['f1_macro_mean'], r['f1_macro_std'])} | {fmt(r.get('ece_mean'), r.get('ece_std'))} | "
                 f"{fmt(r['model_size_mb_mean'], r['model_size_mb_std'], 2)} | {fmt(r['params_reported_mean'], None, 0)} | "
                 f"{fmt(r['stored_weight_elements_mean'], None, 0)} | {fmt(r['cpu_latency_1t_ms_mean'], r['cpu_latency_1t_ms_std'], 2)} | "
                 f"{fmt(r.get('flip_rate_vs_fp32_mean'), r.get('flip_rate_vs_fp32_std'))} |")
lines += ["", "## Shift (accuracy, mean ± std over seeds)", "", "| arch | variant | test set | protocol | accuracy | macro-F1 |",
          "|---|---|---|---|---|---|"]
for _, r in shift_tab.iterrows():
    lines.append(f"| {r['arch']} | {r['experiment']} | {r['test_set']} | {r['protocol']} | "
                 f"{fmt(r['accuracy_mean'], r['accuracy_std'])} | {fmt(r['f1_macro_mean'], r['f1_macro_std'])} |")
(OUT / "summary.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Aggregated {len(idx)} runs -> {OUT}")
print("\n".join(lines[:20]))
